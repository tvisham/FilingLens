"""Golden-set files (JSON Lines under `evals/golden/`).

Financial and cadence rows start as snapshots of the pipeline's own output with
`verified_by = null`; they only count once a person has checked them against the filing
(`filinglens eval label financials|cadence`). Risk-category and coherence labels are
written by `filinglens eval label risk|coherence`. Nothing here is ever generated by an
LLM.

Risk labels are keyed by accession + a hash of the factor heading, not by database ids,
so they survive re-ingestion.
"""

from __future__ import annotations

import hashlib
import json
import re
from collections.abc import Iterable
from datetime import date
from pathlib import Path

from pydantic import BaseModel, Field

GOLDEN_DIR = Path("evals/golden")
FINANCIALS = "financials.jsonl"
CADENCE = "cadence.jsonl"
RISK_LABELS = "risk_labels.jsonl"
COHERENCE_LABELS = "coherence_labels.jsonl"


class FinancialGolden(BaseModel):
    case_id: str  # e.g. AAPL-revenue-FY2026Q4
    ticker: str
    metric: str  # revenue | net_income
    fiscal_year: int
    fiscal_quarter: int
    period_end: date
    value_usd: str  # exact decimal string
    accession: str
    verified_by: str | None = None
    verified_at: date | None = None
    note: str | None = None


class CadenceGolden(BaseModel):
    case_id: str  # e.g. AAPL-10-K-2026-11-24
    ticker: str
    as_of: date
    form: str
    count: int
    verified_by: str | None = None
    verified_at: date | None = None
    note: str | None = None


class RiskLabel(BaseModel):
    case_id: str  # <ticker>-FY<year>-<heading_key>
    ticker: str
    accession: str
    fiscal_year: int
    heading_key: str
    heading: str | None
    categories: list[str] = Field(min_length=1, max_length=3)
    labeler: str
    labeled_at: date


class CoherenceLabel(BaseModel):
    case_id: str  # <scenario>-<input value>
    scenario: str
    output_sha: str  # which agent output was scored
    score: int = Field(ge=1, le=5)
    judge_score: int | None = Field(None, ge=1, le=5)  # the LLM judge's score for the same output
    labeler: str
    labeled_at: date


def heading_key(heading: str | None, text: str) -> str:
    """Stable id for a risk factor across runs: its heading, or its opening words."""
    basis = heading or " ".join(text.split()[:30])
    normalised = " ".join(re.findall(r"[a-z0-9]+", basis.lower()))
    return hashlib.sha1(normalised.encode()).hexdigest()[:12]


def output_sha(output: object) -> str:
    return hashlib.sha1(json.dumps(output, sort_keys=True, default=str).encode()).hexdigest()[:12]


def load[M: BaseModel](model: type[M], name: str, directory: Path = GOLDEN_DIR) -> list[M]:
    path = directory / name
    if not path.exists():
        return []
    rows: list[M] = []
    with path.open(encoding="utf-8") as fh:
        for n, line in enumerate(fh, 1):
            if line.strip():
                try:
                    rows.append(model.model_validate_json(line))
                except ValueError as exc:
                    raise ValueError(f"{path}:{n}: {exc}") from exc
    return rows


def save(rows: Iterable[BaseModel], name: str, directory: Path = GOLDEN_DIR) -> Path:
    """Rewrite the file, one JSON object per line, sorted by case_id for clean diffs."""
    directory.mkdir(parents=True, exist_ok=True)
    path = directory / name
    ordered = sorted(rows, key=lambda r: str(getattr(r, "case_id", "")))
    path.write_text("".join(r.model_dump_json() + "\n" for r in ordered), encoding="utf-8")
    return path


def upsert[M: BaseModel](existing: list[M], new: Iterable[M]) -> list[M]:
    """Replace rows with the same case_id, append the rest."""
    by_id = {str(getattr(r, "case_id")): r for r in existing}  # noqa: B009
    for r in new:
        by_id[str(getattr(r, "case_id"))] = r  # noqa: B009
    return list(by_id.values())
